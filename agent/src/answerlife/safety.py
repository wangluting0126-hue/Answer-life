"""安全层：在调用模型之前，用确定性规则先看一眼这句话。

借鉴 EmoLLM / SoulChat 等心理陪伴项目的做法：危机识别不交给模型"自己领会"，而是规则先行、
模型兜底——规则命中时，固定的求助信息一定会发出去，哪怕模型不可用、哪怕模型回复跑偏。

规则只做"宁可多问一句"的粗筛，不做诊断。命中后 Agent 进入安全模式：暂缓答案页仪式，
先关心此刻是否安全，给出可以立刻联系的人和热线。
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# 有明确的自伤意图、计划或手段
_CRISIS = [
    r"自杀", r"轻生", r"不想活", r"活不下去", r"想死", r"寻死", r"了结自己", r"结束(我|自己)?的?生命",
    r"(我|自己).{0,8}(去死|死了算了|死掉算了|一死了之)", r"不如死了", r"死了(就|也)?(好|解脱|轻松)",
    r"跳楼", r"跳河", r"跳桥", r"割腕", r"烧炭", r"上吊", r"(吞|攒|囤|吃(了|光)).{0,6}(安眠药|药片|一整瓶)",
    r"遗书", r"写好了?告别", r"安排好后事",
    r"\bkill (my ?self|me)\b", r"\bsuicid", r"\bend (my|it all)\b.{0,10}\b(life|all)\b", r"\bwant to die\b",
]
# 正在受到他人的伤害或威胁
_DANGER = [
    r"家暴", r"(他|她|对方|老公|老婆|男友|女友|爸|妈|父亲|母亲).{0,6}(打我|掐我|踢我|推我撞)",
    r"(威胁|扬言).{0,6}(杀|弄死|打死|伤害)我", r"被.{0,4}(打|跟踪|囚禁|关起来)", r"不让我(出门|离开|报警)",
]
# 值得多关心一句，但没有明确意图
_CONCERN = [
    r"自残", r"伤害自己", r"划(自己|手臂|手腕)", r"撑不下去", r"撑不住了", r"绝望", r"没有活着的意义",
    r"活着(好|很|真)?(累|没意思)", r"消失(就|也)?好了", r"不想醒来", r"睡着(就)?别醒", r"崩溃", r"没人在乎我",
]
# 常见口头禅，避免误报
_IDIOM = re.compile(r"(笑|累|饿|困|热|冷|烦|气|尴尬|丑|美|帅|无聊|忙)死(我|了|人)")


@dataclass
class Assessment:
    level: str           # none / concern / danger / crisis
    matched: list[str]

    @property
    def urgent(self) -> bool:
        return self.level in ("crisis", "danger")


def assess(text: str) -> Assessment:
    cleaned = _IDIOM.sub("", text or "")
    lowered = cleaned.lower()
    for level, patterns in (("crisis", _CRISIS), ("danger", _DANGER), ("concern", _CONCERN)):
        hits = [p for p in patterns if re.search(p, lowered)]
        if hits:
            return Assessment(level, hits)
    return Assessment("none", [])


